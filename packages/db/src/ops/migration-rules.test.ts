import { existsSync, readdirSync, readFileSync } from 'node:fs'
import path from 'node:path'
import { describe, expect, it } from 'vitest'
import { MIGRATION_ALLOW_LIST, migrationViolations, splitStatements } from './migration-rules'
import { defaultMigrationsFolder as folder, readJournal } from './migrations'

const journal = readJournal(folder)
const sqlOf = (tag: string) => readFileSync(path.join(folder, `${tag}.sql`), 'utf8')

describe('migration rules (spec §5)', () => {
  it('every migration in packages/db/drizzle is additive, or allow-listed with its two-release plan', () => {
    for (const { tag } of journal) expect(migrationViolations(tag, sqlOf(tag)), tag).toEqual([])
  })

  it('every migration was generated by drizzle-kit: the journal, the SQL files and the snapshots agree', () => {
    const sqlFiles = readdirSync(folder).filter((f) => f.endsWith('.sql')).sort()
    expect(sqlFiles).toEqual(journal.map((e) => `${e.tag}.sql`).sort())
    journal.forEach((entry, i) => {
      const prefix = String(i).padStart(4, '0')
      expect(entry.tag.startsWith(`${prefix}_`), entry.tag).toBe(true)
      expect(existsSync(path.join(folder, 'meta', `${prefix}_snapshot.json`)), entry.tag).toBe(true)
    })
    // no snapshot left behind without a journal entry to match it (e.g. from a migration that was reverted by hand)
    const snapshotFiles = readdirSync(path.join(folder, 'meta')).filter((f) => /^\d{4}_snapshot\.json$/.test(f)).sort()
    expect(snapshotFiles).toEqual(journal.map((_, i) => `${String(i).padStart(4, '0')}_snapshot.json`).sort())
  })

  it('journal timestamps strictly increase, so "the newest applied migration" is unambiguous', () => {
    journal.reduce<(typeof journal)[number] | null>((previous, entry) => {
      if (previous !== null) expect(entry.when, entry.tag).toBeGreaterThan(previous.when)
      return entry
    }, null)
  })

  it('keeps the allow-list honest: every entry still matches a statement and explains its plan', () => {
    for (const allowed of MIGRATION_ALLOW_LIST) {
      expect(allowed.plan.length).toBeGreaterThan(20)
      expect(splitStatements(sqlOf(allowed.tag)).some((s) => allowed.statement.test(s)), allowed.tag).toBe(true)
    }
  })

  it('flags DROP, RENAME, type changes, SET NOT NULL, deletes and concurrent index builds', () => {
    const rules = (text: string) => migrationViolations('0099_new', text).map((v) => v.rule)
    expect(rules('ALTER TABLE "work" DROP COLUMN "subtitle";')).toEqual(['DROP'])
    expect(rules('ALTER TABLE "work" RENAME COLUMN "title" TO "name";')).toEqual(['RENAME'])
    expect(rules('ALTER TABLE "work" ALTER COLUMN "original_year" SET DATA TYPE smallint;')).toEqual(['column type change'])
    expect(rules('ALTER TABLE "work" ALTER COLUMN "language" SET NOT NULL;')).toEqual(['SET NOT NULL'])
    expect(rules('DELETE FROM "tag";')).toEqual(['TRUNCATE or DELETE'])
    expect(rules('CREATE INDEX CONCURRENTLY "x" ON "work" ("title");')).toEqual(['CREATE INDEX CONCURRENTLY (cannot run inside the per-migration transaction)'])
  })

  it('flags a column type change written without SET DATA, and every kind of DROP', () => {
    const rules = (text: string) => migrationViolations('0099_new', text).map((v) => v.rule)
    expect(rules('ALTER TABLE "work" ALTER COLUMN "original_year" TYPE smallint;')).toEqual(['column type change'])
    expect(rules('ALTER TABLE "work" DROP CONSTRAINT "work_pkey";')).toEqual(['DROP'])
    expect(rules('DROP INDEX "work_title_idx";')).toEqual(['DROP'])
    expect(rules('DROP TYPE "job_status";')).toEqual(['DROP'])
    expect(rules('ALTER TYPE "job_status" RENAME VALUE \'queued\' TO \'pending\';')).toEqual(['RENAME'])
  })

  it('does not flag an identifier that merely contains a rule word, like a "drop_reason" column', () => {
    const rules = (text: string) => migrationViolations('0099_new', text).map((v) => v.rule)
    expect(rules('ALTER TABLE "work" ADD COLUMN "drop_reason" text;')).toEqual([])
    expect(rules('ALTER TABLE "work" ADD COLUMN "renamed_at" timestamp with time zone;')).toEqual([])
  })

  it('still flags the allow-listed statement text under a different migration tag', () => {
    const statement = 'ALTER TABLE "loan" DROP CONSTRAINT "loan_borrower_user_id_app_user_id_fk";'
    expect(migrationViolations('0099_new', statement).map((v) => v.rule)).toEqual(['DROP'])
    expect(migrationViolations('0003_sources_proposals_jobs', statement).map((v) => v.rule)).toEqual([])
  })

  it('accepts additive statements, including plain index builds and ON DELETE clauses', () => {
    expect(
      migrationViolations(
        '0099_new',
        'CREATE INDEX "x" ON "work" USING btree ("title");--> statement-breakpoint\nALTER TABLE "work" ADD COLUMN "y" text;--> statement-breakpoint\nALTER TABLE "a" ADD CONSTRAINT "f" FOREIGN KEY ("b") REFERENCES "c"("id") ON DELETE cascade;',
      ),
    ).toEqual([])
  })
})
